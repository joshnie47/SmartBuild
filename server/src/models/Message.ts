import mongoose, { Document, Schema } from 'mongoose';

export type MessageStatus = 'sent' | 'delivered' | 'read';
export type MessageType = 'text' | 'image' | 'document' | 'audio';

export interface IAttachmentMeta {
  fileId: mongoose.Types.ObjectId;       // GridFS file ID in chatAttachments bucket
  filename: string;                       // Safe original filename
  mimeType: string;
  fileSize: number;
}

export interface IMessage extends Document {
  conversationId: mongoose.Types.ObjectId;
  senderId: mongoose.Types.ObjectId;       // Always set by server from JWT — never trusted from client
  clientMessageId: string;                 // UUID generated by client — used for idempotency
  messageType: MessageType;
  body: string;
  attachment?: IAttachmentMeta;
  attachments?: IAttachmentMeta[];
  status: MessageStatus;
  editedAt: Date | null;
  deletedAt: Date | null;                  // Soft delete — message still exists in DB
  createdAt: Date;
  updatedAt: Date;
}

const AttachmentSchema = new Schema<IAttachmentMeta>(
  {
    fileId: {
      type: Schema.Types.ObjectId,
      required: true,
    },
    filename: {
      type: String,
      required: true,
      trim: true,
    },
    mimeType: {
      type: String,
      required: true,
      trim: true,
    },
    fileSize: {
      type: Number,
      required: true,
    },
  },
  { _id: false }
);

const MessageSchema = new Schema<IMessage>(
  {
    conversationId: {
      type: Schema.Types.ObjectId,
      ref: 'Conversation',
      required: true,
      index: true,
    },
    senderId: {
      type: Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
    // UUID v4 sent by the client browser so the server can detect retries
    clientMessageId: {
      type: String,
      required: true,
      trim: true,
    },
    messageType: {
      type: String,
      enum: ['text', 'image', 'document', 'audio'],
      default: 'text',
      index: true,
    },
    body: {
      type: String,
      default: '',
      trim: true,
      maxlength: [4000, 'Message cannot exceed 4000 characters'],
    },
    attachment: {
      type: AttachmentSchema,
      default: undefined,
    },
    attachments: {
      type: [AttachmentSchema],
      default: undefined,
    },
    status: {
      type: String,
      enum: ['sent', 'delivered', 'read'],
      default: 'sent',
    },
    editedAt: { type: Date, default: null },
    deletedAt: { type: Date, default: null },
  },
  { timestamps: true }
);

// Primary query: paginated message history for a conversation
MessageSchema.index({ conversationId: 1, createdAt: 1 });

// Idempotency: prevent duplicate messages from retried sends
MessageSchema.index(
  { conversationId: 1, senderId: 1, clientMessageId: 1 },
  { unique: true }
);

export const Message = mongoose.model<IMessage>('Message', MessageSchema);
